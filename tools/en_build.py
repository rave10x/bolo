"""Build content/en.tsv (Hinglish -> English) from tools/en_ui.py + tools/en_content.json."""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from en_ui import UI
esc = lambda s: s.replace("\\", "\\\\").replace("\n", "\\n").replace("\t", " ")
rows = {}
for k, v in UI: rows[k] = v
for k, v in json.load(open(os.path.join(os.path.dirname(__file__), "en_content.json"), encoding="utf8")).items():
    rows.setdefault(k, v)
out = ["# Hinglish source<TAB>English. Generated by tools/en_build.py"]
for k, v in rows.items():
    out.append(esc(k.strip()) + "\t" + esc(v.strip()))
open(os.path.join(os.path.dirname(__file__), "..", "content", "en.tsv"), "w", encoding="utf8").write("\n".join(out) + "\n")
print(len(out) - 1, "entries")
